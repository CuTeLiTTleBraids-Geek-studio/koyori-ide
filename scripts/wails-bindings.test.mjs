test("CLI probe reports missing and mismatched executables explicitly", () => {
  const missing = Object.assign(new Error("spawn failed"), { code: "ENOENT" });
  assert.throws(
    () => resolvePinnedCLI({
      pinnedVersion: pin,
      env: { WAILS3_BIN: "missing-wails3" },
      spawn: () => ({ error: missing }),
    }),
    /executable not found/,
  );
  assert.throws(
    () => resolvePinnedCLI({
      pinnedVersion: pin,
      env: { WAILS3_BIN: "wrong-wails3" },
      spawn: () => ({ status: 0, stdout: "v3.0.0-alpha2.117\n", stderr: "" }),
    }),
    /version mismatch.*beta\.8.*alpha2\.117/,
  );
  const runner = resolvePinnedCLI({
    pinnedVersion: pin,
    env: { WAILS3_BIN: "pinned-wails3" },
    spawn: () => ({ status: 0, stdout: `${pin}\n`, stderr: "" }),
  });
  assert.equal(runner.command, "pinned-wails3");
});

