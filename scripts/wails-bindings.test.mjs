async function readRepositoryFile(relative) {
  return (await readFile(path.join(repositoryRoot, ...relative.split("/")), "utf8"))
    .replaceAll("\r\n", "\n");
}

function taskBlock(source, name) {
  const marker = `  ${name}:\n`;
  const start = source.indexOf(marker);
  assert.notEqual(start, -1, `missing task ${name}`);
  const remainder = source.slice(start + marker.length);
  const nextOffset = remainder.search(/\n  \S/);
  const next = nextOffset === -1 ? -1 : start + marker.length + nextOffset;
  return source.slice(start, next === -1 ? source.length : next);
}

async function temporaryDirectory(prefix, callback) {
  const directory = await mkdtemp(path.join(os.tmpdir(), prefix));
  try {
    await callback(directory);
  } finally {
    await rm(directory, { recursive: true, force: true });
  }
}

async function writeGenerated(directory, relative, source) {
  const full = path.join(directory, ...relative.split("/"));
  await mkdir(path.dirname(full), { recursive: true });
  await writeFile(full, source, "utf8");
}

