test("directory audit rejects missing, empty, stale, extra, FQN and forbidden exports", async () => {
  await temporaryDirectory("koyori-ide-bindings-unit-", async (directory) => {
    const relative = "github.com/CuTeLiTTleBraids-Geek-studio/koyori-ide/services/fileservice.ts";
    const clean = `${generatedMarker}export function ReadFile() { return $Call.ByID(1); }\n`;
    await writeGenerated(directory, relative, clean);
    const manifest = await createBindingsManifest(directory, pin);

    const missingErrors = await auditBindingsDirectory(path.join(directory, "absent"), manifest);
    assert.match(missingErrors.join("\n"), /missing bindings directory/);

    const empty = path.join(directory, "empty");
    await mkdir(empty);
    const emptyErrors = await auditBindingsDirectory(empty, manifest);
    assert.match(emptyErrors.join("\n"), /bindings directory is empty/);

    await writeGenerated(directory, relative, `${clean}// drift\n`);
    let errors = await auditBindingsDirectory(directory, manifest);
    assert.match(errors.join("\n"), /stale or modified generated file/);

    await writeGenerated(directory, relative, clean);
    await writeGenerated(directory, "unexpected.ts", generatedMarker);
    errors = await auditBindingsDirectory(directory, manifest);
    assert.match(errors.join("\n"), /unexpected generated file/);

    const byName = `${generatedMarker}export function ReadFile() { return $Call.ByName("bad.FQN"); }\n`;
    await rm(path.join(directory, "unexpected.ts"));
    await writeGenerated(directory, relative, byName);
    const byNameManifest = await createBindingsManifest(directory, pin);
    errors = await auditBindingsDirectory(directory, byNameManifest);
    assert.match(errors.join("\n"), /name-based FQN call/);

    const forbidden = `${generatedMarker}export function SetWorkspaceRoot() { return $Call.ByID(2); }\n`;
    await writeGenerated(directory, relative, forbidden);
    const forbiddenManifest = await createBindingsManifest(directory, pin);
    errors = await auditBindingsDirectory(directory, forbiddenManifest);
    assert.match(errors.join("\n"), /forbidden export SetWorkspaceRoot/);

    await writeGenerated(directory, relative, clean);
    const settingsRelative = "github.com/CuTeLiTTleBraids-Geek-studio/koyori-ide/services/settingsservice.ts";
    for (const method of [
      "GetSecret",
      "StoreSecret",
      "DeleteSecret",
      "GetExtensionSecret",
      "StoreExtensionSecret",
      "DeleteExtensionSecret",
    ]) {
      await writeGenerated(
        directory,
        settingsRelative,
        `${generatedMarker}export function ${method}() { return $Call.ByID(3); }\n`,
      );
      const secretManifest = await createBindingsManifest(directory, pin);
      errors = await auditBindingsDirectory(directory, secretManifest);
      assert.match(errors.join("\n"), new RegExp(`forbidden export ${method}`));
    }
  });
});

