  assert.match(androidCompile, /- task: generate:android:overlay/);
  assert.match(taskBlock(android, "compile:go:all-archs"), /\n    internal: true\n/);
  assert.match(taskBlock(android, "assemble:apk"), /eq \.PIPELINE_OWNER "android-run"/);
  assert.match(taskBlock(android, "assemble:apk:release"), /eq \.PIPELINE_OWNER "android-package"/);
