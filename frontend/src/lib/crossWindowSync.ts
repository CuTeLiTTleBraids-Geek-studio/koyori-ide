// 架构改进 B (prompt-1.md): 跨窗口事件总线与 store 边界。
//
// 边界约定：跨窗口（main ↔ AI companion window）通信用 Wails Events；窗口
// 内部状态用 reactive store。本模块是唯一的「事件 → store 动作」编排层，
// 在应用启动时调用 initCrossWindowSync() 一次性接线，teardownCrossWindowSync()
// 用于 HMR / 测试清理。
//
// 事件 → store 映射表（全仓库 Events.On 站点）：
//   ┌──────────────────────────┬─────────────────────────────┬──────────────────┐
//   │ 事件                     │ 处理方                      │ 集中化状态       │
//   ├──────────────────────────┼─────────────────────────────┼──────────────────┤
//   │ window:maximised         │ app handler                 │ 已迁移至本模块   │
//   │ settings:changed         │ app handler                 │ 已迁移至本模块   │
//   │ project:removed          │ app handler                 │ 已迁移至本模块   │
//   │ workspace:changed        │ workspace authority         │ 已迁移至本模块   │
//   │ ai:apply-to-editor       │ editor.requestApplyToEditor │ 已迁移至本模块   │
//   │ ai:chunk/done/error/...  │ ai.ensureEventListeners     │ 本模块统一编排     │
//   │ terminal:output/exited   │ terminal.ensureEventListener│ TODO: 迁移至本模块 │
//   │ file:saved (workflows)   │ workflows.initWorkflowTriggers│ TODO: 迁移至本模块 │
//   │ workflow:completed       │ workflows.initWorkflowTriggers│ TODO: 迁移至本模块 │
// Koyori IDE 模块 · Cross Window Sync。
// 喵，这是 Koyori IDE 的 Cross Window Sync 模块（前端实现）~
//   │ file:saved (testExplorer)│ testExplorer.initContinuousTesting│ TODO: 迁移至本模块 │
//   │ agent:pending-updated    │ agent.initAgentPendingSync  │ 本模块统一编排     │
//   │ conversation:saved      │ AI store + local subscribers│ 已迁移至本模块   │
//   │ ai:selection             │ local subscribers           │ 已迁移至本模块   │
//   │ ai-window:maximised      │ local subscribers           │ 已迁移至本模块   │
//   └──────────────────────────┴─────────────────────────────┴──────────────────┘
//
// 注：store 仍拥有依赖私有状态的事件处理器；本模块拥有应用主路径的注册与注销
// 时机。这样既避免暴露 pendingAssistantMessage 等内部状态，也确保 bootstrap、
// HMR 和窗口卸载只有一条对称生命周期路径。

